-- ============================================================
-- STEP 1: ORGANIZATIONS (the new top-level tenant entity)
-- ============================================================

CREATE TABLE IF NOT EXISTS organizations (
  id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name                TEXT NOT NULL,
  brand_logo_url      TEXT,
  brand_primary_color TEXT,
  brand_secondary_color TEXT,
  subscription_plan   TEXT NOT NULL DEFAULT 'trial'
                        CHECK (subscription_plan IN ('trial', 'flat', 'per_seat', 'hybrid')),
  status              TEXT NOT NULL DEFAULT 'active'
                        CHECK (status IN ('active', 'suspended', 'trial')),
  owner_contact_email TEXT,
  created_at          TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_organizations_status ON organizations(status);

-- Seed Sunshine Lab's own organization as the first tenant, so existing
-- rows have somewhere to point once organization_id is backfilled below.
INSERT INTO organizations (name, status, subscription_plan, owner_contact_email)
SELECT 'Sunshine Lab', 'active', 'trial', 'shani@echo5digital.com'
WHERE NOT EXISTS (SELECT 1 FROM organizations WHERE name = 'Sunshine Lab');


-- ============================================================
-- STEP 2: organization_id ON EXISTING TABLES
-- ============================================================

-- admin_users: null organization_id = platform super admin
ALTER TABLE admin_users ADD COLUMN IF NOT EXISTS organization_id UUID REFERENCES organizations(id);

-- Expand role check to include org_admin alongside the existing
-- super_admin / admin / staff values already in use.
-- (Looked up by information_schema instead of assuming the
-- Postgres-autogenerated constraint name, since the original
-- CHECK on admin_users.role was declared inline/unnamed.)
DO $$
DECLARE
  cname TEXT;
BEGIN
  SELECT con.conname INTO cname
  FROM pg_constraint con
  JOIN pg_class rel ON rel.oid = con.conrelid
  WHERE rel.relname = 'admin_users'
    AND con.contype = 'c'
    AND pg_get_constraintdef(con.oid) ILIKE '%role%';

  IF cname IS NOT NULL THEN
    EXECUTE format('ALTER TABLE admin_users DROP CONSTRAINT %I', cname);
  END IF;
END $$;

ALTER TABLE admin_users ADD CONSTRAINT admin_users_role_check
  CHECK (role IN ('super_admin', 'admin', 'org_admin', 'staff'));

CREATE INDEX IF NOT EXISTS idx_admin_users_organization ON admin_users(organization_id);

-- Backfill: every existing admin_users row that isn't already super_admin
-- belongs to Sunshine Lab's own organization.
UPDATE admin_users
SET organization_id = (SELECT id FROM organizations WHERE name = 'Sunshine Lab')
WHERE organization_id IS NULL
  AND role != 'super_admin';


-- appointments: tenant column + field-visit columns
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS organization_id UUID REFERENCES organizations(id);
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS assigned_staff_id UUID REFERENCES admin_users(id);
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS check_in_at TIMESTAMPTZ;
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS check_in_lat DOUBLE PRECISION;
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS check_in_lng DOUBLE PRECISION;
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS check_out_at TIMESTAMPTZ;
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS check_out_lat DOUBLE PRECISION;
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS check_out_lng DOUBLE PRECISION;
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS visit_notes TEXT;
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS signature_file_url TEXT;

-- Backfill all existing appointments to Sunshine Lab's own organization.
UPDATE appointments
SET organization_id = (SELECT id FROM organizations WHERE name = 'Sunshine Lab')
WHERE organization_id IS NULL;

CREATE INDEX IF NOT EXISTS idx_appointments_organization ON appointments(organization_id);
CREATE INDEX IF NOT EXISTS idx_appointments_org_date ON appointments(organization_id, appointment_date);
CREATE INDEX IF NOT EXISTS idx_appointments_org_staff_status ON appointments(organization_id, assigned_staff_id, status);


-- ============================================================
-- STEP 3: SUBSCRIPTIONS (billing, Phase 2 — created now so the
-- foreign key story is complete from Phase 0 onward)
-- ============================================================

CREATE TABLE IF NOT EXISTS subscriptions (
  id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id        UUID NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  plan_tier              TEXT NOT NULL DEFAULT 'trial',
  seat_count             INTEGER NOT NULL DEFAULT 1,
  billing_status         TEXT NOT NULL DEFAULT 'trialing'
                           CHECK (billing_status IN ('trialing', 'active', 'past_due', 'cancelled')),
  renewal_date           DATE,
  stripe_customer_id     TEXT,
  stripe_subscription_id TEXT,
  created_at             TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_subscriptions_organization ON subscriptions(organization_id);


-- ============================================================
-- STEP 4: NEW org-scoped RLS policies — ADDED ALONGSIDE existing ones
--
-- IMPORTANT — DOES NOT TOUCH "appointments_admin_all" / "appointments_staff_read":
-- Those two existing policies are left exactly as-is. They already grant
-- authenticated admin/staff roles the access this app currently relies on
-- (today inert in practice, since the backend queries via the service-role
-- key — see rls-policies.sql header — but they are the correct fallback for
-- the day that changes). Nothing here drops or replaces them.
--
-- The new policies below are strictly ADDITIVE and organization-scoped.
-- They will not conflict with the existing ones (Postgres RLS is OR'd
-- across permissive policies for the same command), and they are
-- effectively no-ops until organization_id is added as a JWT claim in
-- authRoutes.js (out of scope for this SQL-only migration — flagged as
-- a required follow-up below, NOT bundled into this script).
--
-- Do NOT delete "appointments_admin_all" / "appointments_staff_read" in a
-- follow-up until authRoutes.js actually issues organization_id in the
-- token AND that's been verified end-to-end. Removing them early would
-- silently zero out authenticated-role access to appointments.
-- ============================================================

-- super_admin: unrestricted, org-scoped table added on top
DROP POLICY IF EXISTS "appointments_super_admin_all" ON appointments;
CREATE POLICY "appointments_super_admin_all"
ON appointments
FOR ALL
TO authenticated
USING ((auth.jwt() ->> 'role') = 'super_admin')
WITH CHECK ((auth.jwt() ->> 'role') = 'super_admin');

-- org_admin: full CRUD, scoped to their own organization
DROP POLICY IF EXISTS "appointments_org_admin_scoped" ON appointments;
CREATE POLICY "appointments_org_admin_scoped"
ON appointments
FOR ALL
TO authenticated
USING (
  (auth.jwt() ->> 'role') = 'org_admin'
  AND organization_id::text = (auth.jwt() ->> 'organization_id')
)
WITH CHECK (
  (auth.jwt() ->> 'role') = 'org_admin'
  AND organization_id::text = (auth.jwt() ->> 'organization_id')
);

-- staff: can update ONLY the visit-capture fields on their own assigned
-- appointments (check-in/out, notes, signature) — not reassign, delete,
-- or edit patient/billing fields. Enforced at the application layer
-- (to be added); this RLS policy is the defense-in-depth backstop.
DROP POLICY IF EXISTS "appointments_staff_visit_update" ON appointments;
CREATE POLICY "appointments_staff_visit_update"
ON appointments
FOR UPDATE
TO authenticated
USING (
  (auth.jwt() ->> 'role') = 'staff'
  AND organization_id::text = (auth.jwt() ->> 'organization_id')
  AND assigned_staff_id::text = (auth.jwt() ->> 'id')
)
WITH CHECK (
  (auth.jwt() ->> 'role') = 'staff'
  AND organization_id::text = (auth.jwt() ->> 'organization_id')
  AND assigned_staff_id::text = (auth.jwt() ->> 'id')
);

-- NOTE: no new staff-read or admin-read org-scoped policy is added here,
-- because "appointments_admin_all" (role IN ('super_admin','admin')) and
-- "appointments_staff_read" (role = 'staff') already cover read access
-- for those roles unscoped. Once organization_id is live in the JWT and
-- the plan is to make staff/admin reads tenant-scoped too, that's a
-- follow-up migration that DROPs the old unscoped policies at the same
-- time it confirms the new claim is flowing — not bundled here.


-- organizations table: only super_admin manages tenants directly;
-- org_admin can read/update only their own row (branding settings, Phase 2)
ALTER TABLE organizations ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "organizations_super_admin_all" ON organizations;
CREATE POLICY "organizations_super_admin_all"
ON organizations
FOR ALL
TO authenticated
USING ((auth.jwt() ->> 'role') = 'super_admin')
WITH CHECK ((auth.jwt() ->> 'role') = 'super_admin');

DROP POLICY IF EXISTS "organizations_org_admin_self_read" ON organizations;
CREATE POLICY "organizations_org_admin_self_read"
ON organizations
FOR SELECT
TO authenticated
USING (id::text = (auth.jwt() ->> 'organization_id'));

DROP POLICY IF EXISTS "organizations_anon_deny" ON organizations;
CREATE POLICY "organizations_anon_deny"
ON organizations
FOR ALL
TO anon
USING (FALSE)
WITH CHECK (FALSE);


-- subscriptions table: super_admin only for now (billing is Phase 2)
ALTER TABLE subscriptions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "subscriptions_super_admin_all" ON subscriptions;
CREATE POLICY "subscriptions_super_admin_all"
ON subscriptions
FOR ALL
TO authenticated
USING ((auth.jwt() ->> 'role') = 'super_admin')
WITH CHECK ((auth.jwt() ->> 'role') = 'super_admin');

DROP POLICY IF EXISTS "subscriptions_anon_deny" ON subscriptions;
CREATE POLICY "subscriptions_anon_deny"
ON subscriptions
FOR ALL
TO anon
USING (FALSE)
WITH CHECK (FALSE);


-- ============================================================
-- STEP 5: SUPER ADMIN AUDIT LOG
-- Every unscoped (cross-tenant) access by a super_admin is recorded here.
-- ============================================================

CREATE TABLE IF NOT EXISTS super_admin_audit_log (
  id                      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  admin_id                UUID REFERENCES admin_users(id),
  admin_email             TEXT,
  action                  TEXT NOT NULL,
  target_organization_id  UUID REFERENCES organizations(id),
  details                 JSONB,
  created_at              TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_audit_log_admin ON super_admin_audit_log(admin_id);
CREATE INDEX IF NOT EXISTS idx_audit_log_org ON super_admin_audit_log(target_organization_id);
CREATE INDEX IF NOT EXISTS idx_audit_log_created ON super_admin_audit_log(created_at DESC);

ALTER TABLE super_admin_audit_log ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "audit_log_super_admin_read" ON super_admin_audit_log;
CREATE POLICY "audit_log_super_admin_read"
ON super_admin_audit_log
FOR SELECT
TO authenticated
USING ((auth.jwt() ->> 'role') = 'super_admin');

-- Inserts happen only via the backend's service-role key (bypasses RLS) —
-- no authenticated-role write policy is needed or wanted here.
DROP POLICY IF EXISTS "audit_log_anon_deny" ON super_admin_audit_log;
CREATE POLICY "audit_log_anon_deny"
ON super_admin_audit_log
FOR ALL
TO anon
USING (FALSE)
WITH CHECK (FALSE);


